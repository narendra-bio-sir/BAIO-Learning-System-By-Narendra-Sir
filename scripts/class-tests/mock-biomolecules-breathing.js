// Mock test (30 marks, 1 hr 15 min): I PUC Biology, Ch 9 Biomolecules + Ch 14 Breathing and Exchange of Gases.
// All 14 questions of the 20-mark monthly test, shuffled within each part, plus 8 more question-bank questions,
// in the chapter pattern of the official I PUC Biology Blue Print 2026-27 (Ch 9: 1-mark and 5-mark only;
// Ch 14: 2-mark and 3-mark only):
//   Part A: 8 MCQ + 3 fill-ups (Ch 9, all) · Part B: any 4 of 6 × 2 (Ch 14) · Part C: any 2 of 3 × 3 (Ch 14)
//   · Part D: any 1 of 2 × 5 (Ch 9) = 30 marks (Ch 9 : Ch 14 = 16 : 14).
// Builds 3 PDFs into exam-corner/pu-board-2026-27/ (…-30m.pdf, …-30m-answer-key.pdf, …-30m-blueprint.pdf) and
// writes exam-corner/bio-breathing-mock-data.js for biomolecules-breathing-mock-practice.html (same questions, same order).
// Run: NODE_PATH=<global node_modules with playwright> node scripts/class-tests/mock-biomolecules-breathing.js
const fs = require('fs'), path = require('path');
const {Q, IMG, build, writePdfs, order, ROOT} = require('./bio-breathing-bank');
const MONTHLY = require('./monthly-biomolecules-breathing');

const monthlyIds = order(MONTHLY);
const MOCK = {
  kind: 'MOCK TEST', base: 'biology-i-puc-mock-test-biomolecules-and-breathing-30m', time: '1 hour 15 minutes', total: 30,
  parts: {
    mcq: ['adenosine', 'valine', 'rubisco', 'rate', 'compet', 'galactose', 'ester', 'transition'],
    fib: ['cellulose', 'cytosine', 'water'],
    B: {ids: ['ppressure', 'organs', 'vctlc', 'emphysema', 'animals', 'tidal'], n: 4},
    C: {ids: ['haemoglobin', 'larynx', 'mechanism'], n: 2},
    D: {ids: ['proteins', 'enzymes'], n: 1}
  },
  words: ['Cellulose', 'Cytosine', 'Lipids', 'Water'], extraWord: 'Lipids', monthlyIds,
  /* the 22-question paper is tightened a little so it stays on one page */
  tight: 'body{font-size:10.4pt;line-height:1.24}.q{margin:2px 0}.sec{margin:6px 0 2px}.ins{margin-bottom:6px;padding:4px 9px}.who{margin:4px 0 6px}.hd{padding-bottom:4px;margin-bottom:6px}'
};
const all = order(MOCK);
for (const id of monthlyIds) if (!all.includes(id)) throw new Error('monthly question missing from the mock: ' + id);
MOCK.keyNote = `<b>M</b> marks the ${monthlyIds.length} questions of the 20-mark monthly test, all included here in a shuffled order; the other ${all.length - monthlyIds.length} questions are added to make up the 30-mark pattern.`;

/* ---- data for the in-app practice page ---- */
function appData(){
  const P = MOCK.parts, pick = (id) => Q[id];
  const chapters = [], page = [], marks = [];
  for (let i = 0; i <= 14; i++) { chapters.push(''); page.push(''); marks.push(0); }
  chapters[9] = 'Biomolecules'; chapters[14] = 'Breathing and Exchange of Gases'; page[9] = 'pu1-ch9.html';
  marks[9] = P.mcq.length + P.fib.length + P.D.n * 5; marks[14] = P.B.n * 2 + P.C.n * 3;
  const long = (ids) => ids.map(id => { const q = pick(id); const o = {id, ch: q.ch, q: q.q, p: q.p, m: q.m}; if (q.img) o.img = q.img; return o; });
  return {
    chapters, page, marks,
    mcq: P.mcq.map(id => { const q = pick(id); return {ch: q.ch, q: q.q, o: q.o, a: q.a, e: q.e}; }),
    fibWords: MOCK.words.slice(),
    fib: P.fib.map(id => { const q = pick(id); return {ch: q.ch, q: q.q, a: q.a, e: q.e}; }),
    B: long(P.B.ids), C: long(P.C.ids), D: long(P.D.ids), D2: [],
    diagrams: [
      {t: 'Human respiratory system (NCERT Fig. 14.1)', ch: 14, img: IMG.resp, labels: ['Epiglottis', 'Larynx', 'Trachea', 'Bronchus', 'Bronchiole', 'Alveoli', 'Lung', 'Pleural membranes', 'Pleural fluid', 'Diaphragm', 'Heart', 'Cut end of rib']},
      {t: 'Oxygen dissociation curve (NCERT Fig. 14.5)', ch: 14, img: IMG.odc, labels: ['X-axis: partial pressure of oxygen (mm Hg)', 'Y-axis: percentage saturation of haemoglobin with oxygen', 'Sigmoid (S-shaped) curve', 'Scale 0–100 on both axes']},
      {t: 'Concept of activation energy (NCERT Fig. 9.4)', ch: 9, img: IMG.ae, labels: ['Y-axis: potential energy', 'X-axis: progress of reaction', 'Substrate (S)', 'Product (P)', 'Transition state', 'Activation energy without enzyme', 'Activation energy with enzyme']}
    ]
  };
}
