#!/usr/bin/env python3
"""Builds exam-corner/pu2-report-data.js from the PU2_STUDENTS results in analytics.html.
The Exam Corner print/PDF of the personal timetable uses it for the marks snapshot and
Narendra Sir's remarks. Run after updating results in analytics.html:
    python3 scripts/build-pu2-report.py
"""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, 'analytics.html'), encoding='utf-8').read()
m = re.search(r'const PU2_STUDENTS = (\[.*?\]);\n', src, re.S)
students = json.loads(m.group(1))
SUBJ = ['KAN', 'HIN', 'ENG', 'PHY', 'CHE', 'MAT', 'BIO', 'ELE']
EARLIER = ['march', 'april', 'may', 'june', 'july']
out = {}
for s in students:
    code = s['code'][-4:]
    pm = s.get('premid') or {}
    marks = {k: pm.get(k) for k in SUBJ if pm.get(k) is not None}
    earlier = []
    for key in EARLIER:
        r = s.get(key) or {}
        vals = [r[k] for k in SUBJ if isinstance(r.get(k), (int, float))]
        if vals:
            earlier.append(round(sum(vals) / (40 * len(vals)) * 100, 1))
    out[code] = {'m': marks, 'r': pm.get('RANK'), 'e': earlier}
js = ('/* Generated by scripts/build-pu2-report.py from analytics.html — do not edit by hand.\n'
      '   Per enrollment no.: m = Pre-Midterm marks (each /40), r = class rank, e = earlier monthly test %. */\n'
      'window.PU2_REPORT = ' + json.dumps(out, separators=(',', ':')) + ';\n')
open(os.path.join(ROOT, 'exam-corner', 'pu2-report-data.js'), 'w', encoding='utf-8').write(js)
print(len(out), 'students')
