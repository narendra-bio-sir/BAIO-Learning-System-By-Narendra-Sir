/* Builds careers/student-data.js for the personalised Career Guidance report.
   Loads analytics.html in headless Chromium and reuses its own calculations
   (class percentile, NEET / KCET / JEE readiness), so the numbers match the
   teacher's analytics exactly.

   Each record is stored under sha256(ROLL + '|' + REPORT-CARD PASSWORD), so a
   student's results can only be opened with the same password as their report card.

   Run from the repo root after updating analytics.html:
       node scripts/build-career-data.js
*/
const fs = require('fs'), path = require('path'), http = require('http'), crypto = require('crypto');
const { chromium } = require('playwright');
const ROOT = path.join(__dirname, '..');

function serve(){
  return new Promise(res => {
    const srv = http.createServer((req, rsp) => {
      const p = path.join(ROOT, decodeURIComponent(req.url.split('?')[0]));
      fs.readFile(p, (e, d) => { if(e){ rsp.writeHead(404); rsp.end(); return; } rsp.writeHead(200, {'Content-Type': p.endsWith('.html') ? 'text/html' : 'application/octet-stream'}); rsp.end(d); });
    }).listen(0, () => res(srv));
  });
}

(async () => {
  const srv = await serve();
  const b = await chromium.launch();
  const page = await (await b.newContext({ serviceWorkers: 'block' })).newPage();
  await page.route(/^https?:\/\/(?!127\.0\.0\.1)/, r => r.abort());
  await page.goto('http://127.0.0.1:' + srv.address().port + '/analytics.html', { waitUntil: 'load' });
  await page.waitForTimeout(500);
  const rows = await page.evaluate(() => {
    const out = [];
    const r1 = x => x == null ? null : Math.round(x * 10) / 10;
    function exam(cat, s, pu){
      let r = null; try{ r = computeStudentExamReadiness(cat, s, pu); }catch(e){}
      if(!r) return null;
      return { p: r1(r.latestPct), tr: r1(r.trend), n: r.attemptsCount, lb: r.latestLabel, sc: r.latestTotalScore, mx: r.latestTotalMax,
               sub: (r.latestSubjects || []).filter(x => x.score != null).map(x => [x.label, x.score, x.max]) };
    }
    function subjects(s, pu){
      // Average % per subject over the monthly / mid-term theory tests (each subject out of 40; Sept I PUC out of 20).
      const keys = pu === 2 ? ['march','april','may','june','july','premid'] : ['june','mt','august','september'];
      const max = k => (pu === 1 && k === 'september') ? 20 : 40;
      const acc = {};
      keys.forEach(k => { const t = s[k]; if(!t) return; ['PHY','CHE','BIO','MAT'].forEach(sb => {
        const v = t[sb]; if(v == null || isNaN(v)) return; (acc[sb] = acc[sb] || []).push(100 * v / max(k)); }); });
      const o = {}; Object.keys(acc).forEach(sb => { o[sb] = r1(acc[sb].reduce((a, b) => a + b, 0) / acc[sb].length); });
      return o;
    }
    function add(s, pu){
      const th = computeClassPercentileTrend(s, pu);
      const last = th && th.points.length ? th.points[th.points.length - 1] : null;
      out.push({ code: s.code, name: s.name, sec: s.section, pu,
        th: th ? { p: th.avgPct, tr: th.trend, n: th.points.length, rk: last.rank, of: last.n, lb: last.label } : null,
        sub: subjects(s, pu),
        neet: exam('neet', s, pu), kpcb: exam('kcetpcb', s, pu), kpcm: exam('kcet', s, pu), jee: exam('jee', s, pu) });
    }
    STUDENTS.forEach(s => add(s, 1));
    PU2_STUDENTS.forEach(s => add(s, 2));
    return { rows: out, pw1: REPORT_CARD_PASSWORDS, pw2: PU2_REPORT_CARD_PASSWORDS, master: ANALYTICS_MASTER_CODE };
  });
  await b.close(); srv.close();

  const data = {}, index = []; let n = 0, skipped = 0;
  rows.rows.forEach(r => {
    const pw = (r.pu === 2 ? rows.pw2 : rows.pw1)[r.code];
    if(!pw){ skipped++; return; }
    const key = crypto.createHash('sha256').update(r.code.toUpperCase() + '|' + String(pw).toUpperCase()).digest('hex');
    const rec = Object.assign({}, r); delete rec.code;
    data[key] = rec; n++;
    index.push({ r: r.code, n: r.name, s: r.sec, pu: r.pu, k: key });
  });
  /* Teacher index: every student's roll, name and record key, encrypted (AES-GCM) with a key
     derived from the analytics master code, so only Narendra Sir can list and open any report. */
  const salt = crypto.randomBytes(16), iv = crypto.randomBytes(12);
  const tk = crypto.pbkdf2Sync(String(rows.master).toUpperCase(), salt, 150000, 32, 'sha256');
  const cipher = crypto.createCipheriv('aes-256-gcm', tk, iv);
  const plain = JSON.stringify(index.sort((a, b) => a.pu - b.pu || String(a.n).localeCompare(String(b.n))));
  const ct = Buffer.concat([cipher.update(plain, 'utf8'), cipher.final(), cipher.getAuthTag()]);
  const teacher = { s: salt.toString('base64'), i: iv.toString('base64'), c: ct.toString('base64') };
  const js = '/* Generated by scripts/build-career-data.js from analytics.html — do not edit by hand.\n'
    + '   Key = sha256(ROLL|REPORT-CARD PASSWORD). th = theory class percentile, sub = subject average %,\n'
    + '   neet/kpcb/kpcm/jee = exam readiness (p = latest %, tr = trend, sub = [subject, score, max]). */\n'
    + 'window.CAREER_STUDENTS = ' + JSON.stringify(data) + ';\n'
    + 'window.CAREER_TEACHER = ' + JSON.stringify(teacher) + ';\n';
  fs.writeFileSync(path.join(ROOT, 'careers', 'student-data.js'), js);
  console.log('students written:', n, '· without a report-card password (skipped):', skipped);
})();
